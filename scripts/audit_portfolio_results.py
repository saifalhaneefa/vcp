"""Audit executed VCP portfolio trades.

Reads the portfolio_trades.csv and portfolio_equity.csv generated by
backtest_portfolio.py and summarizes trade distribution, holding time,
exit reasons, yearly results, and concentration in the largest winners.

Run:
    python scripts/audit_portfolio_results.py
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def pct(x: float) -> str:
    return f"{x:.2%}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--trades",
        type=Path,
        default=PROJECT_ROOT / "reports" / "portfolio_trades.csv",
    )
    parser.add_argument(
        "--equity",
        type=Path,
        default=PROJECT_ROOT / "reports" / "portfolio_equity.csv",
    )
    args = parser.parse_args()

    if not args.trades.exists():
        raise SystemExit(f"Trade report not found: {args.trades}")
    if not args.equity.exists():
        raise SystemExit(f"Equity report not found: {args.equity}")

    trades = pd.read_csv(args.trades)
    equity = pd.read_csv(args.equity)

    if trades.empty:
        raise SystemExit("Trade report is empty.")

    trades["signal_date"] = pd.to_datetime(trades["signal_date"])
    trades["entry_date"] = pd.to_datetime(trades["entry_date"])
    trades["exit_date"] = pd.to_datetime(trades["exit_date"])
    trades["holding_days"] = (
        trades["exit_date"] - trades["entry_date"]
    ).dt.days

    trades["entry_year"] = trades["entry_date"].dt.year

    out = PROJECT_ROOT / "reports"
    out.mkdir(exist_ok=True)

    # Normalize the equity curve once so the calendar-year portfolio
    # performance section and the final equity check use the same data.
    if "equity" in equity.columns:
        equity["Date"] = pd.to_datetime(equity.iloc[:, 0])
        equity = equity.sort_values("Date").reset_index(drop=True)

    print("=" * 100)
    print("VCP PORTFOLIO TRADE AUDIT")
    print("=" * 100)

    print(f"Trades: {len(trades)}")
    print(f"Symbols traded: {trades['symbol'].nunique()}")
    print(
        f"Date range: {trades['entry_date'].min().date()} -> "
        f"{trades['exit_date'].max().date()}"
    )

    winners = trades[trades["pnl"] > 0]
    losers = trades[trades["pnl"] <= 0]

    print("\nTRADE DISTRIBUTION")
    print(f"Winning trades: {len(winners)} ({len(winners) / len(trades):.2%})")
    print(f"Losing trades:  {len(losers)} ({len(losers) / len(trades):.2%})")
    print(f"Median trade return: {trades['return_pct'].median():.2%}")
    print(f"Mean trade return:   {trades['return_pct'].mean():.2%}")
    print(f"Median R:             {trades['r_multiple'].median():.2f}")
    print(f"Mean R:               {trades['r_multiple'].mean():.2f}")
    print(f"Median holding days:  {trades['holding_days'].median():.0f}")
    print(f"Mean holding days:    {trades['holding_days'].mean():.1f}")
    print(f"Trades > 250 days:    {(trades['holding_days'] > 250).sum()}")
    print(f"Trades > 500 days:    {(trades['holding_days'] > 500).sum()}")
    print(f"Trades > 1000 days:   {(trades['holding_days'] > 1000).sum()}")
    print(
        f"Best trade:           {trades.loc[trades['return_pct'].idxmax(), 'symbol']} "
        f"{trades['return_pct'].max():.2%}"
    )
    print(
        f"Worst trade:          {trades.loc[trades['return_pct'].idxmin(), 'symbol']} "
        f"{trades['return_pct'].min():.2%}"
    )

    print("\nEXIT REASONS")
    print(trades["exit_reason"].value_counts().to_string())

    print("\nYEARLY TRADE RESULTS")
    yearly = trades.groupby("entry_year").agg(
        trades=("symbol", "size"),
        wins=("pnl", lambda s: int((s > 0).sum())),
        total_pnl=("pnl", "sum"),
        mean_return=("return_pct", "mean"),
        median_return=("return_pct", "median"),
        mean_r=("r_multiple", "mean"),
        median_r=("r_multiple", "median"),
    )
    yearly["win_rate"] = yearly["wins"] / yearly["trades"]
    print(yearly.to_string(formatters={
        "total_pnl": "₹{:,.0f}".format,
        "mean_return": "{:.2%}".format,
        "median_return": "{:.2%}".format,
        "mean_r": "{:.2f}".format,
        "median_r": "{:.2f}".format,
        "win_rate": "{:.2%}".format,
    }))

    if "equity" in equity.columns:
        print("\nCALENDAR-YEAR PORTFOLIO PERFORMANCE")
        calendar_rows = []
        previous_year_end = None

        for year, year_data in equity.groupby(equity["Date"].dt.year, sort=True):
            year_data = year_data.sort_values("Date").reset_index(drop=True)
            first_equity = float(year_data["equity"].iloc[0])
            end_equity = float(year_data["equity"].iloc[-1])
            start_equity = (
                first_equity if previous_year_end is None else previous_year_end
            )

            # Drawdown for the calendar year is measured from the prior
            # year-end equity (or the first available equity point for the
            # first year), so the table describes the portfolio path during
            # that year rather than trade-entry cohorts.
            dd_series = pd.concat(
                [
                    pd.Series([start_equity], dtype=float),
                    year_data["equity"].astype(float),
                ],
                ignore_index=True,
            )
            peak_series = dd_series.cummax()
            year_dd = dd_series / peak_series - 1.0
            dd_idx = int(year_dd.idxmin())
            if dd_idx == 0:
                dd_date = year_data["Date"].iloc[0].date()
            else:
                dd_date = year_data["Date"].iloc[dd_idx - 1].date()

            calendar_rows.append(
                {
                    "year": int(year),
                    "start_equity": start_equity,
                    "end_equity": end_equity,
                    "total_pnl": end_equity - start_equity,
                    "annual_return": end_equity / start_equity - 1.0,
                    "max_drawdown": float(year_dd.min()),
                    "drawdown_date": dd_date,
                }
            )
            previous_year_end = end_equity

        calendar_year = pd.DataFrame(calendar_rows).set_index("year")
        print(
            calendar_year.to_string(
                formatters={
                    "start_equity": "₹{:,.0f}".format,
                    "end_equity": "₹{:,.0f}".format,
                    "total_pnl": "₹{:,.0f}".format,
                    "annual_return": "{:.2%}".format,
                    "max_drawdown": "{:.2%}".format,
                }
            )
        )

        calendar_year.to_csv(out / "portfolio_calendar_year_results.csv")
        print(
            f"Saved: {out / 'portfolio_calendar_year_results.csv'}"
        )

    print("\nTOP 10 WINNERS")
    top = trades.nlargest(10, "pnl")[
        [
            "symbol", "signal_date", "entry_date", "exit_date",
            "return_pct", "r_multiple", "pnl", "holding_days",
            "exit_reason",
        ]
    ]
    print(top.to_string(index=False, formatters={
        "return_pct": "{:.2%}".format,
        "r_multiple": "{:.2f}".format,
        "pnl": "₹{:,.0f}".format,
    }))

    total_positive = winners["pnl"].sum()
    top5_positive = winners.nlargest(5, "pnl")["pnl"].sum()
    print("\nPROFIT CONCENTRATION")
    print(f"Gross profit from winning trades: ₹{total_positive:,.0f}")
    print(
        f"Top 5 winners contribution: "
        f"{top5_positive / total_positive:.2%}"
        if total_positive > 0
        else "Top 5 winners contribution: n/a"
    )

    print("\nTRADE RETURN QUANTILES")
    quantiles = trades["return_pct"].quantile(
        [0.0, 0.1, 0.25, 0.5, 0.75, 0.9, 1.0]
    )
    print("\n".join(
        f"{q:>4.0%}: {value:.2%}" for q, value in quantiles.items()
    ))

    if "equity" in equity.columns:
        eq_col = "equity"
        eq = equity[eq_col].astype(float)
        peak = eq.cummax()
        dd = eq / peak - 1.0
        print("\nEQUITY CHECK")
        print(f"Ending equity: ₹{eq.iloc[-1]:,.2f}")
        print(f"Max drawdown: {dd.min():.2%}")
        print(
            f"Date of max drawdown: "
            f"{equity.loc[dd.idxmin(), 'Date'].date()}"
        )
        print(f"Days with drawdown below -20%: {(dd < -0.20).sum()}")

    trades.sort_values("pnl", ascending=False).to_csv(
        out / "portfolio_trades_audited.csv", index=False
    )
    print(f"\nSaved: {out / 'portfolio_trades_audited.csv'}")


if __name__ == "__main__":
    main()
